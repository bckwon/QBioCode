#!/usr/bin/env bash
#==============================================================================
# LSF Job Array: L3 PCA dimension sweep — K=4, all 22 endpoints
#
# 22 endpoints × 3 featurisers = 66 tasks (QSVC with n_components=4)
# The K=4 sweep covers all endpoints to establish whether performance
# degrades at extreme low dimension across the full benchmark.
#
# Runtime estimate: ~90 min/task.
# Total: ~99 GPU-hours across 66 tasks.
#
# Submit from repo root:
#   bsub < experiments/admet_benchmark/lsf/job_L3_pca_sweep_k4.sh
#==============================================================================
#BSUB -J admet_pca_k4[1-66]
#BSUB -q normal
#BSUB -n 1
#BSUB -R "span[hosts=1]"
#BSUB -R "rusage[mem=4000]"
#BSUB -m "zu-a100-b05-02 zu-a100-c06-01 zu-a100-c08-02 zu-a100-c08-03"
#BSUB -gpu "num=1:mode=shared:j_exclusive=no"
#BSUB -o logs/admet/l3_pca_k4_%I_%J.out
#BSUB -e logs/admet/l3_pca_k4_%I_%J.err
#BSUB -cwd /proj/bmfm/users/bckwon/projects/QBioCode
#BSUB -r
#BSUB -nr 2

set -euo pipefail

REPO_ROOT="/proj/bmfm/users/bckwon/projects/QBioCode"
cd "${REPO_ROOT}"
export PATH="${REPO_ROOT}/.venv/bin:${PATH}"
export PYTHONPATH="${REPO_ROOT}"

# Task list generated by 10_generate_task_list.py
# Format: "K:::ENDPOINT:::FEAT"  (K is always 4 here)
source experiments/admet_benchmark/lsf/l3a_task_list.sh

TASK="${TASKS[${LSB_JOBINDEX}]}"
K="${TASK%%:::*}"
REST="${TASK#*:::}"
ENDPOINT="${REST%%:::*}"
FEAT="${REST##*:::}"

# Use original full data (PCA is fit at runtime from train.csv)
INPUT_DIR="${REPO_ROOT}/data/admet/${ENDPOINT}/${FEAT}"
CONFIG="${REPO_ROOT}/qbiocode/apps/qprofiler/configs/admet_qsvc_pca_${K}.yaml"
DATA_TYPE="${ENDPOINT}_${FEAT}_qsvc_pca${K}"
LOG="${REPO_ROOT}/logs/admet/l3_pca_${ENDPOINT}_${FEAT}_k${K}_${LSB_JOBID:-local}.log"

echo "======================================================"
echo "Job ${LSB_JOBID:-local}[${LSB_JOBINDEX}]  $(hostname)  $(date)"
echo "K=${K}  Endpoint=${ENDPOINT}  Feat=${FEAT}  (QSVC PCA sweep)"
echo "Input: ${INPUT_DIR}"
echo "Config: ${CONFIG}"
echo "======================================================"

if [ ! -f "${INPUT_DIR}/train_qml.csv" ]; then
    echo "[ERROR] train_qml.csv not found: ${INPUT_DIR}/train_qml.csv"
    exit 1
fi

PYTHONPATH="${REPO_ROOT}" qprofiler-batch \
    --input-dir  "${INPUT_DIR}" \
    --config     "${CONFIG}" \
    --data-type  "${DATA_TYPE}" \
    --n-jobs     1 \
    2>&1 | tee "${LOG}"

EXIT_CODE=${PIPESTATUS[0]}
echo ""
echo "======================================================"
echo "End time  : $(date)"
echo "Exit code : ${EXIT_CODE}"
echo "======================================================"
exit ${EXIT_CODE}
