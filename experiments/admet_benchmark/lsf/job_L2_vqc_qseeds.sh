#!/usr/bin/env bash
#==============================================================================
# LSF Job Array: L2 VQC quantum-seed (q_seed) sweep
#
# 9 q_seeds × 3 priority endpoints × 3 featurisers = 81 tasks
# Priority endpoints: CYP2C9_Substrate_CarbonMangels,
#                     Clearance_Hepatocyte_AZ,
#                     CYP2D6_Substrate_CarbonMangels
#
# Training data stays fixed at data/admet/{ep}/{feat}/train_qml.csv (seed=42).
# Only the quantum circuit initialisation seed (q_seed) changes.
#
# Runtime estimate: ~30–60 min/task on a single GPU.
# Total: ~50–80 GPU-hours across 81 tasks.
#
# Submit from repo root:
#   bsub < experiments/admet_benchmark/lsf/job_L2_vqc_qseeds.sh
#==============================================================================
#BSUB -J admet_vqc_qseeds[1-81]
#BSUB -q normal
#BSUB -n 6
#BSUB -R "span[hosts=1]"
#BSUB -R "rusage[mem=16000]"
#BSUB -m "zu-a100-b05-02 zu-a100-c06-01 zu-a100-c08-02"
#BSUB -gpu "num=1:mode=shared:j_exclusive=no"
#BSUB -o logs/admet/l2_vqc_qseeds_%I_%J.out
#BSUB -e logs/admet/l2_vqc_qseeds_%I_%J.err
#BSUB -cwd /proj/bmfm/users/bckwon/projects/QBioCode
#BSUB -r
#BSUB -nr 2

set -euo pipefail

REPO_ROOT="/proj/bmfm/users/bckwon/projects/QBioCode"
cd "${REPO_ROOT}"
export PATH="${REPO_ROOT}/.venv/bin:${PATH}"
export PYTHONPATH="${REPO_ROOT}"

# Task list generated by 10_generate_task_list.py
# Format: "QSEED:::ENDPOINT:::FEAT"
source experiments/admet_benchmark/lsf/l2_task_list.sh

TASK="${TASKS[${LSB_JOBINDEX}]}"
QSEED="${TASK%%:::*}"
REST="${TASK#*:::}"
ENDPOINT="${REST%%:::*}"
FEAT="${REST##*:::}"

# Data stays at the original seed=42 train_qml.csv
INPUT_DIR="${REPO_ROOT}/data/admet/${ENDPOINT}/${FEAT}"
CONFIG="${REPO_ROOT}/qbiocode/apps/qprofiler/configs/admet_vqc_qseed_${QSEED}.yaml"
DATA_TYPE="${ENDPOINT}_${FEAT}_vqc_qseed${QSEED}"
LOG="${REPO_ROOT}/logs/admet/l2_vqc_${ENDPOINT}_${FEAT}_qseed${QSEED}_${LSB_JOBID:-local}.log"

echo "======================================================"
echo "Job ${LSB_JOBID:-local}[${LSB_JOBINDEX}]  $(hostname)  $(date)"
echo "QSeed=${QSEED}  Endpoint=${ENDPOINT}  Feat=${FEAT}  (VQC q_seed sweep)"
echo "Input: ${INPUT_DIR}"
echo "Config: ${CONFIG}"
echo "======================================================"

if [ ! -f "${INPUT_DIR}/train_qml.csv" ]; then
    echo "[ERROR] train_qml.csv not found: ${INPUT_DIR}/train_qml.csv"
    exit 1
fi

PYTHONPATH="${REPO_ROOT}" qprofiler-batch \
    --input-dir  "${INPUT_DIR}" \
    --config     "${CONFIG}" \
    --data-type  "${DATA_TYPE}" \
    --n-jobs     1 \
    2>&1 | tee "${LOG}"

EXIT_CODE=${PIPESTATUS[0]}
echo ""
echo "======================================================"
echo "End time  : $(date)"
echo "Exit code : ${EXIT_CODE}"
echo "======================================================"
exit ${EXIT_CODE}
