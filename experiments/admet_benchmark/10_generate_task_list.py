#!/usr/bin/env python3
"""
Generate LSF task list files for L1 and L2 ablation job arrays.

Outputs:
  experiments/admet_benchmark/lsf/l1_task_list.sh   — 264 tasks (L1 QSVC/cl300 seeds)
  experiments/admet_benchmark/lsf/l2_task_list.sh   — 81 tasks  (L2 VQC q_seeds)
  experiments/admet_benchmark/lsf/l3a_task_list.sh  — 66 tasks  (L3 K=4, all endpoints)
  experiments/admet_benchmark/lsf/l3b_task_list.sh  — 54 tasks  (L3 K=12,16,32, priority)

Usage (run AFTER 08_generate_seed_splits.py):
    .venv/bin/python3 experiments/admet_benchmark/10_generate_task_list.py
"""
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
LSF_DIR = REPO / "experiments/admet_benchmark/lsf"
LSF_DIR.mkdir(parents=True, exist_ok=True)

SEEDS = [0, 21, 84, 100]
Q_SEEDS = [0, 7, 21, 73, 84, 100, 123, 200, 314]
ENDPOINTS = [
    "AMES", "BBB_Martins", "Bioavailability_Ma", "CYP1A2_Veith",
    "CYP2C19_Veith", "CYP2C9_Substrate_CarbonMangels", "CYP2C9_Veith",
    "CYP2D6_Substrate_CarbonMangels", "CYP2D6_Veith",
    "CYP3A4_Substrate_CarbonMangels", "CYP3A4_Veith", "Caco2_Wang",
    "Clearance_Hepatocyte_AZ", "DILI", "HIA_Hou", "Half_Life_Obach",
    "Lipophilicity_AstraZeneca", "PPBR_AstraZeneca", "Pgp_Broccatelli",
    "Solubility_AqSolDB", "VDss_Lombardo", "hERG",
]
PRIORITY_EPS = [
    "CYP2C9_Substrate_CarbonMangels",
    "Clearance_Hepatocyte_AZ",
    "CYP2D6_Substrate_CarbonMangels",
]
FEATS = ["ecfp4", "maccs", "rdkit200"]
PCA_DIMS_PRIORITY = [12, 16, 32]


def write_task_list(path: Path, header: str, entries: list[str]) -> None:
    lines = [
        f"# Auto-generated by 10_generate_task_list.py",
        f"# {header}",
        "TASKS=(",
        '    ""  # 0 unused (LSF is 1-based)',
    ]
    for i, entry in enumerate(entries, start=1):
        lines.append(f'    "{entry}"  # {i}')
    lines.append(")")
    path.write_text("\n".join(lines) + "\n")
    print(f"Wrote {path}  ({len(entries)} tasks)")


# ── L1: seed ablation (4 seeds × 22 eps × 3 feats = 264) ────────────────────
l1_entries = []
for seed in SEEDS:
    for ep in ENDPOINTS:
        for feat in FEATS:
            src = REPO / "data/admet_seeds" / f"seed_{seed}" / ep / feat / "train_qml.csv"
            if src.exists():
                l1_entries.append(f"{seed}:::{ep}:::{feat}")
            else:
                print(f"  WARNING L1: missing {src}")

write_task_list(
    LSF_DIR / "l1_task_list.sh",
    "L1 seed ablation: SEED:::ENDPOINT:::FEAT",
    l1_entries,
)

# ── L2: VQC q_seed sweep (9 q_seeds × 3 eps × 3 feats = 81) ─────────────────
l2_entries = []
for qs in Q_SEEDS:
    for ep in PRIORITY_EPS:
        for feat in FEATS:
            l2_entries.append(f"{qs}:::{ep}:::{feat}")

write_task_list(
    LSF_DIR / "l2_task_list.sh",
    "L2 VQC q_seed sweep: QSEED:::ENDPOINT:::FEAT",
    l2_entries,
)

# ── L3a: PCA K=4, all 22 endpoints × 3 feats = 66 ────────────────────────────
l3a_entries = []
for ep in ENDPOINTS:
    for feat in FEATS:
        l3a_entries.append(f"4:::{ep}:::{feat}")

write_task_list(
    LSF_DIR / "l3a_task_list.sh",
    "L3 PCA sweep K=4, all endpoints: K:::ENDPOINT:::FEAT",
    l3a_entries,
)

# ── L3b: PCA K=12,16,32, 6 priority endpoints × 3 feats = 54 ────────────────
PRIORITY_EPS_L3 = [
    "CYP2C9_Substrate_CarbonMangels",
    "Clearance_Hepatocyte_AZ",
    "CYP2D6_Substrate_CarbonMangels",
    "Bioavailability_Ma",
    "BBB_Martins",
    "PPBR_AstraZeneca",
]
l3b_entries = []
for K in PCA_DIMS_PRIORITY:
    for ep in PRIORITY_EPS_L3:
        for feat in FEATS:
            l3b_entries.append(f"{K}:::{ep}:::{feat}")

write_task_list(
    LSF_DIR / "l3b_task_list.sh",
    "L3 PCA sweep K=12,16,32, priority endpoints: K:::ENDPOINT:::FEAT",
    l3b_entries,
)

print(f"\nL1: {len(l1_entries)} tasks, L2: {len(l2_entries)} tasks, "
      f"L3a: {len(l3a_entries)} tasks, L3b: {len(l3b_entries)} tasks")
